import { chromium } from "@playwright/test";
const b = await chromium.launch({ headless: true });
const ctx = await b.newContext({ viewport: { width: 1440, height: 900 } });
const p = await ctx.newPage();
const cerr = []; p.on("console", m => { if (m.type()==="error" && !/favicon|devtools/i.test(m.text())) cerr.push(m.text()); });
const perr = []; p.on("pageerror", e => perr.push(String(e)));
await p.goto("https://firekaro.com/", { waitUntil: "networkidle", timeout: 30000 });
await p.waitForTimeout(2500);
const url = p.url();
const body = (await p.locator("body").innerText().catch(()=> "")).replace(/\s+/g," ");
const hasLogin = /sign in|google|log ?in|firekaro/i.test(body);
await p.screenshot({ path: "verification-screenshots/PROD-login.png", fullPage: true });
console.log("final URL:", url);
console.log("login markers present:", hasLogin);
console.log("body excerpt:", body.slice(0,180));
console.log("console errors:", cerr.length ? JSON.stringify(cerr) : "none");
console.log("page errors:", perr.length ? JSON.stringify(perr) : "none");
console.log("VERDICT:", (hasLogin && perr.length===0) ? "PASS" : "CHECK");
await b.close();
